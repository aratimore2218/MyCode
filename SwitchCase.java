package Module2;

public class SwitchCase {
	public static void main(String[]args)
	
	{
		switch(0)
		{
		case 1: System.out.println("Change your language");
	        	break;
		case 2: System.out.println("Withdraw money");
    	break;
		case 3: System.out.println("Deposite money");
    	break;
		case 4: System.out.println("Change my pin");
    	break;
		case 5: System.out.println("Check balance");
    	break;
    	
    	default:
    		System.out.println("Take your card out and insert again");
        }

    }
}
